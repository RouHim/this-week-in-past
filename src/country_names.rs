/// Returns the English short name for an ISO-3166 alpha-2 `code`,
/// or `None` for unknown codes. Matching is case-insensitive and
/// whitespace-tolerant; no allocation on the lookup path.
pub fn country_name(code: &str) -> Option<&'static str> {
    let bytes = code.trim().as_bytes();
    if bytes.len() != 2 {
        return None;
    }
    let key = [bytes[0].to_ascii_uppercase(), bytes[1].to_ascii_uppercase()];
    COUNTRIES
        .binary_search_by(|(c, _)| c.as_bytes().cmp(&key))
        .ok()
        .map(|i| COUNTRIES[i].1)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn table_is_sorted_and_complete() {
        assert!(
            COUNTRIES.len() >= 240,
            "expected full ISO table, got {} entries",
            COUNTRIES.len()
        );
        let mut prev = "";
        for (code, name) in COUNTRIES {
            assert!(*code > prev, "table not sorted at {}", code);
            assert_eq!(code.len(), 2, "code {} is not 2 letters", code);
            assert!(!name.is_empty(), "empty name for {}", code);
            prev = code;
        }
    }

    #[test]
    fn lookup_spot_checks() {
        assert_eq!(country_name("DE"), Some("Germany"));
        assert_eq!(country_name("dk"), Some("Denmark"));
        assert_eq!(country_name(" GB "), Some("United Kingdom"));
        assert_eq!(country_name("US"), Some("United States"));
        assert_eq!(country_name("NO"), Some("Norway"));
        assert_eq!(country_name("XX"), None);
        assert_eq!(country_name(""), None);
        assert_eq!(country_name("D"), None);
        assert_eq!(country_name("DEU"), None);
    }
}
